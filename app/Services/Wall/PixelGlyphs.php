    public const FONTS = ['classic', 'narrow', 'slanted'];

    public function glyph(string $font, int $size, string $letter): array
    {
        $rows = explode('/', self::LETTERS[$letter]);
        $width = max(3, (int) round($size * ($font === 'narrow' ? 3 : 5) / 7));
        $pixels = [];
        for ($y = 0; $y < $size; $y++) {
            $sourceY = (int) round($y * 6 / ($size - 1));
            for ($x = 0; $x < $width; $x++) {
                $sourceX = (int) round($x * 4 / ($width - 1));
                if ($rows[$sourceY][$sourceX] === '1') {
                    $pixels[] = [$x + ($font === 'slanted' ? (int) floor(($size - 1 - $y) / 4) : 0), $y];
                }
            }
        }

        return $pixels;
    }

    public function catalog(): array
    {
        static $catalog;
        if ($catalog !== null) {
            return $catalog;
        }
        $catalog = ['sizes' => [], 'fonts' => []];
        foreach (range(5, 14) as $size) {
            $fonts = [];
            foreach (self::FONTS as $font) {
                foreach (array_keys(self::LETTERS) as $letter) {
                    $glyph = $this->glyph($font, $size, (string) $letter);
                    if (count($glyph) >= 50) {
                        continue 3;
                    }
                    $fonts[$font][$letter] = $glyph;
                }
            }
            $catalog['sizes'][] = $size;
            foreach ($fonts as $font => $letters) {
                $catalog['fonts'][$font][$size] = $letters;
            }
        }

        return $catalog;
    }
